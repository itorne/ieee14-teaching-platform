"""
Analysis of the classroom evaluation (concept test pre/post and System Usability Scale).

Input : evaluation/responses.csv (one row per participant, anonymous code only)
        columns: code, pre_q1..pre_q10, post_q1..post_q10, sus1..sus10
        pre_/post_ items: 1 = correct, 0 = wrong or blank
        sus items: 1..5 (1 = strongly disagree, 5 = strongly agree), standard SUS wording
Output: evaluation/eval_macros.tex (read by the manuscript) and evaluation/eval_summary.csv

Without responses.csv, the script writes "pending" macros so the manuscript still compiles.

Methods:
  * Class-average normalized gain <g> = (post% - pre%) / (100 - pre%) (Hake, 1998).
  * Wilcoxon signed-rank test on paired scores, two-sided; effect size r = |Z| / sqrt(N),
    with Z from the normal approximation (ties and zero differences handled by scipy).
  * SUS score per participant: odd items (x - 1), even items (5 - x), sum x 2.5 (Brooke, 1996);
    mean with t-based 95% CI; grade from the Sauro-Lewis curved scale (Lewis & Sauro, 2018);
    Cronbach's alpha of the ten item contributions.
"""

from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

HERE = Path(__file__).parent
N_ITEMS = 10

GRADES = [(84.1, "A+"), (80.8, "A"), (78.9, "A-"), (77.2, "B+"), (74.1, "B"), (72.6, "B-"),
          (71.1, "C+"), (65.0, "C"), (62.7, "C-"), (51.7, "D"), (0.0, "F")]


def grade(score):
    for lo, g in GRADES:
        if score >= lo:
            return g
    return "F"


def cronbach_alpha(items: np.ndarray) -> float:
    k = items.shape[1]
    var_items = items.var(axis=0, ddof=1).sum()
    var_total = items.sum(axis=1).var(ddof=1)
    return float(k / (k - 1) * (1 - var_items / var_total)) if var_total > 0 else float("nan")


def write(macros: dict):
    lines = ["% Generated by evaluation/analyze_evaluation.py -- do not edit by hand."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    (HERE / "eval_macros.tex").write_text("\n".join(lines) + "\n")


def main():
    path = HERE / "responses.csv"
    names = ["evalN", "evalPre", "evalPost", "evalGain", "evalWilcoxonP", "evalEffectR",
             "evalSUS", "evalSUSci", "evalSUSgrade", "evalSUSalpha", "evalNsusAboveAvg"]
    if not path.exists() or pd.read_csv(path).empty:
        write({k: r"\textbf{[pending]}" for k in names})
        print("responses.csv not found or empty: wrote pending macros.")
        return
    df = pd.read_csv(path)
    pre = df[[f"pre_q{i}" for i in range(1, N_ITEMS + 1)]].sum(axis=1) * 100 / N_ITEMS
    post = df[[f"post_q{i}" for i in range(1, N_ITEMS + 1)]].sum(axis=1) * 100 / N_ITEMS
    paired = pre.notna() & post.notna()
    pre, post = pre[paired], post[paired]
    n = int(paired.sum())
    g = (post.mean() - pre.mean()) / (100 - pre.mean()) if pre.mean() < 100 else float("nan")
    w = stats.wilcoxon(post, pre, zero_method="wilcox", alternative="two-sided", method="approx")
    z = stats.norm.isf(w.pvalue / 2)
    r = z / np.sqrt(n)

    sus_items = df[[f"sus{i}" for i in range(1, 11)]].dropna()
    contrib = sus_items.to_numpy(float).copy()
    contrib[:, 0::2] = contrib[:, 0::2] - 1
    contrib[:, 1::2] = 5 - contrib[:, 1::2]
    sus = contrib.sum(axis=1) * 2.5
    m, s, ns = sus.mean(), sus.std(ddof=1), len(sus)
    half = stats.t.ppf(0.975, ns - 1) * s / np.sqrt(ns) if ns > 1 else float("nan")

    p_txt = "$p < 0.001$" if w.pvalue < 0.001 else f"$p = {w.pvalue:.3f}$"
    write({"evalN": str(n), "evalPre": f"{pre.mean():.1f}", "evalPost": f"{post.mean():.1f}",
           "evalGain": f"{g:.2f}", "evalWilcoxonP": p_txt, "evalEffectR": f"{r:.2f}",
           "evalSUS": f"{m:.1f}", "evalSUSci": f"{m - half:.1f}--{m + half:.1f}", "evalSUSgrade": grade(m),
           "evalSUSalpha": f"{cronbach_alpha(contrib):.2f}", "evalNsusAboveAvg": str(int((sus > 68).sum()))})
    pd.DataFrame({"n_paired": [n], "pre_mean": [pre.mean()], "post_mean": [post.mean()], "normalized_gain": [g],
                  "wilcoxon_p": [w.pvalue], "effect_r": [r], "n_sus": [ns], "sus_mean": [m], "sus_sd": [s],
                  "sus_ci_low": [m - half], "sus_ci_high": [m + half], "sus_grade": [grade(m)],
                  "sus_alpha": [cronbach_alpha(contrib)]}).to_csv(HERE / "eval_summary.csv", index=False)
    print(open(HERE / "eval_macros.tex").read())


if __name__ == "__main__":
    main()
